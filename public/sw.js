/**
 * Service worker — минимальный, намеренно.
 *
 * ЗАЧЕМ ОН ВООБЩЕ. Chrome не предложит «установить приложение» без
 * зарегистрированного SW с обработчиком fetch — это условие установки, а не
 * наша прихоть.
 *
 * ПОЧЕМУ НИЧЕГО НЕ КЕШИРУЕМ. Чат без сети бесполезен: ответы приходят с
 * сервера, история тоже. Кеш оболочки дал бы «приложение открылось, но пустое»
 * — хуже честного сообщения браузера об отсутствии сети. А устаревший кеш
 * оболочки после выката ломал бы приложение до ручной очистки.
 *
 * Поэтому fetch проксируем в сеть как есть. Появится оффлайн-сценарий, ради
 * которого стоит рисковать кешем, — тогда и добавим, осознанно.
 */

// Пропускаем ожидание: свежий SW не должен ждать закрытия всех вкладок, иначе
// исправление в нём доедет до пользователя через недели.
self.addEventListener("install", () => self.skipWaiting());

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      // Чужие кеши прошлых версий (если когда-то кешировали) — вычищаем.
      const keys = await caches.keys();
      await Promise.all(keys.map((k) => caches.delete(k)));
      await self.clients.claim();
    })(),
  );
});

// Обработчик обязателен для критерия установки, но ничего не меняет: запрос
// уходит в сеть. respondWith не зовём вовсе — так браузер обрабатывает запрос
// своим обычным путём, включая потоковые ответы (SSE стриминга ответов).
self.addEventListener("fetch", () => {});
