/** Подключения на карточке агента: что рисовать по конфигу и чем подписывать.
 *
 *  ОТДЕЛЬНО ОТ РАЗМЕТКИ, чтобы это можно было проверить тестом: здесь прячутся
 *  отказы, которые глазом не увидишь. Подпись собирается из значений, пришедших
 *  с сервера, и если однажды в них попадёт секретное поле, оно окажется
 *  напечатанным в карточке агента — то есть пароль на экране.
 */
import type { AgentConnection, ConnectionForm } from "@/lib/api";

/** Формы подключений из конфига агента. Пусто — у агента подключений нет.
 *
 *  Читается ИЗ ЗАПИСИ АГЕНТА, а не запросом на каждую карточку: кнопка
 *  «появляется, если конфиг об этом говорит» — буквально. Раньше каждая
 *  карточка била в API, включая пользовательских агентов, у которых подключений
 *  не бывает, и получала 404.
 */
export function connectionForms(config: Record<string, unknown> | null | undefined): ConnectionForm[] {
  const raw = config?.connection_forms;
  if (!Array.isArray(raw)) return [];
  return raw.filter(
    (f): f is ConnectionForm =>
      typeof f === "object" && f !== null && typeof (f as ConnectionForm).kind === "string" && Array.isArray((f as ConnectionForm).fields),
  );
}

/** Первое непустое ОТКРЫТОЕ поле, или "" — подписывать нечем.
 *
 *  Порядок берём из описания (поля идут в том порядке, в каком их объявил
 *  конфиг): какое поле главное, знает тот, кто описал вид подключения. Прибей
 *  здесь «login» — и этот код знал бы про Exchange, чего он знать не должен.
 *
 *  Секретные ПРОПУСКАЕМ, хотя сервер их и не присылает: два независимых условия
 *  на одну утечку. Перестань сервер фильтровать — пароль всё равно не попадёт на
 *  экран, и наоборот.
 */
export function connectionSubtitle(conn: AgentConnection): string {
  for (const f of conn.fields) {
    if (f.secret) continue;
    const v = conn.values[f.name];
    if (v) return v;
  }
  return "";
}
